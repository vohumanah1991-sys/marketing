export const GATES = {
  /**
   * انتخاب سوژه‌ی کمپین — نه قضاوت درباره‌ی کسب‌وکار.
   *
   * فقط یک کار می‌کند: می‌گوید کمپین را حول کدام محصولات می‌شود ساخت.
   * ناموجودی ایراد نیست — موجودی می‌چرخد. فقط یعنی این محصول الان سوژه نیست.
   */
  usableProducts(knowledge) {
    const list = knowledge?.productUsability || [];
    const usable   = list.filter(p => p.usable === 'yes');
    const excluded = list.filter(p => p.usable === 'no');
    const unsure   = list.filter(p => p.usable === 'unknown' || p.basis === 'page_level');

    return {
      usable,
      excluded,
      unsure,                      // ← اینها را باید از کاربر پرسید، نه حدس زد
      enough: usable.length >= 2,
      // یک سؤال کوتاه، نه یکی‌یکی
      askUser: unsure.length
        ? `این ${unsure.length} قلم را الان دارید؟ ${unsure.slice(0, 8).map(p => p.product).join('، ')}`
        : null,
      note: usable.length === 0 && list.length > 0
        ? 'از عرضه‌هایی که دیدم هیچ‌کدام قطعاً قابل خرید نبود. کدام‌ها را داری تا کمپین را حولشان بسازم؟'
        : null
    };
  },

  /**
   * رسیدن — تنها چیزی که در سطح کسب‌وکار واقعاً مهم است،
   * چون روی *همه‌ی* پست‌ها می‌نشیند، نه یک محصول.
   *
   * هشدار است، نه سد. blocking همیشه false.
   */
  reachCheck(knowledge) {
    const r = knowledge?.reach || {};
    const issues = [];
    if (r.brokenLinks?.length) {
      issues.push({ what: 'لینکی که مشتری باید رویش بزند باز نمی‌شود', detail: r.brokenLinks.join('، '), weight: 3 });
    }
    if ((r.orderPaths?.length || 0) > 3) {
      issues.push({ what: 'مسیرهای سفارش پراکنده', detail: `${r.orderPaths.length} راه مختلف`, weight: 1 });
    }
    const score = issues.reduce((s, i) => s + i.weight, 0);
    return {
      level: score >= 3 ? 'warn' : 'ok',
      issues,
      blocking: false,   // ← همیشه
      caveat: score >= 3
        ? 'لینکی که در محتوا می‌گذاریم باز نمی‌شود. تا درست نشود، هر پستی نیمه‌کاره می‌ماند.'
        : null
    };
  },

  // دروازه ۱ — آیا اجازه‌ی ساخت کارت استراتژی داریم؟
  canBuildStrategy(knowledge) {
    const required = ['business.category', 'products', 'audience'];
    const missing = required.filter(p => !hasValue(knowledge, p));
    return { pass: missing.length === 0, missing };
  },

  // دروازه ۲ — آیا اجازه‌ی تولید محتوا داریم؟
  canProduceContent(card) {
    if (!card?.approvedAt) return { pass: false, reason: 'کارت استراتژی تأیید نشده' };
    if (!card?.prediction?.observable) return { pass: false, reason: 'پیش‌بینی ثبت نشده' };
    return { pass: true };
  },

  // دروازه ۳ — آیا جمله‌ی اول قابل نمایش است؟
  canShowInsight(insight) {
    return { pass: insight.confident >= 0.6, reason: insight.fallback };
  },

  // دروازه ۴ — آیا محتوا قابل انتشار است؟
  // آخرین ایست. در طلا/نقره/سلامت/مالی/حقوقی هرگز دور زده نمی‌شود.
  canPublish(evidenceReport) {
    const bad = (evidenceReport?.claims || [])
      .filter(c => c.kind === 'verifiable' && c.status !== 'ok');
    const needsUser = (evidenceReport?.claims || [])
      .filter(c => ['needsPermission', 'needsConfirmation'].includes(c.status));
    return {
      pass: bad.length === 0 && needsUser.length === 0,
      blocked:  bad.filter(c => c.status === 'blocked'),
      stale:    bad.filter(c => c.status === 'needsRecheck'),
      askUser:  needsUser   // اینها سد نیستند — فقط یک تأیید لازم دارند
    };
  }
};

function hasValue(obj, path) {
  const v = path.split('.').reduce((o, k) => o?.[k], obj);
  if (Array.isArray(v)) return v.length > 0;
  return v?.status === 'fact' || v?.status === 'hypothesis';
}

