// تقویم میلادی — لازم است چون کسب‌وکار ممکن است هرجای دنیا باشد.
// نسخه‌ی اول فقط شمسی را می‌فهمید و برای یک کلینیک لندنی هیچ تاریخی حساب نشد.
const EN_MONTHS = [
  ['january','ژانویه'],['february','فوریه'],['march','مارس'],['april','آوریل'],
  ['may','مه','می'],['june','ژوئن'],['july','ژوئیه'],['august','اوت','آگوست'],
  ['september','سپتامبر'],['october','اکتبر'],['november','نوامبر'],['december','دسامبر']
];

export function upcomingOccasions(market, today = new Date()) {
  return (market?.demandCalendar || [])
    .map(o => ({ ...o, daysUntil: daysUntil(o.approxDate, today) }))
    .filter(o => o.daysUntil != null)
    .sort((a, b) => a.daysUntil - b.daysUntil);
}

function dayInMonth(s) {
  const m = String(s).match(/(\d+)/);
  if (m) return Math.min(parseInt(m[1], 10), 28);
  if (/اواخر|late|end/i.test(s)) return 25;
  if (/اواسط|mid/i.test(s))      return 15;
  return 5;
}

function daysUntil(approx, today) {
  if (!approx) return null;
  const s = String(approx).toLowerCase();

  // اول شمسی
  const fi = FA_MONTHS.findIndex(m => s.includes(m));
  if (fi >= 0) {
    const [gm, gd] = FA_START[fi];
    return diff(new Date(today.getFullYear(), gm - 1, gd + dayInMonth(s) - 1), today);
  }

  // بعد میلادی
  const ei = EN_MONTHS.findIndex(names => names.some(n => s.includes(n)));
  if (ei >= 0) return diff(new Date(today.getFullYear(), ei, dayInMonth(s)), today);

  // فصل‌ها
  const seasons = { spring: 2, autumn: 8, fall: 8, summer: 5, winter: 11,
                    'بهار': 2, 'تابستان': 5, 'پاییز': 8, 'زمستان': 11 };
  for (const [k, mo] of Object.entries(seasons))
    if (s.includes(k)) return diff(new Date(today.getFullYear(), mo, 15), today);

  return null;
}

function diff(target, today) {
  if (target < today) target.setFullYear(target.getFullYear() + 1);
  return Math.round((target - today) / 86400000);
}

/**
 * کهنگی — هر گزاره‌ی بازار تاریخ انقضای خودش را دارد.
 * محرک بیرونی بعد از یک هفته کهنه است، فصلی‌بودن بعد از یک سال.
 */
export function isStale(item, recordedAt, today = new Date()) {
  if (!item?.validDays || !recordedAt) return null;
  const age = Math.round((today - new Date(recordedAt)) / 86400000);
  return { age, stale: age > item.validDays, validDays: item.validDays };
}

/**
 * تعدیل ظرفیت — ظرفیتی که کاربر اعلام می‌کند همیشه خوش‌بینانه است.
 *
 * این از یک مشاهده‌ی واقعی آمد: کاربری گفت «هفته‌ای دو سه ساعت»،
 * بعد دو پست از چهار پست را منتشر نکرد.
 *
 * ضریب ثابت است تا وقتی داده‌ی واقعی جمع شود؛ بعد از چند دور،
 * نسبت «منتشرشده به برنامه‌ریزی‌شده» جای این ضریب را می‌گیرد.
 */
export function realisticCapacity({ statedPerWeek, card, windowDays, history = [] }) {
  const stated = Number(statedPerWeek) || 0;

  // پنجره از خود کارت می‌آید، نه از یک عدد ثابت —
  // کمپین باید دقیقاً به اندازه‌ای طول بکشد که پیش‌بینی برایش سنجیده می‌شود.
  const days  = Number(windowDays) || Number(card?.prediction?.checkAfterDays) || 14;
  const weeks = days / 7;

  // دوری که به دلیل بیرونی هیچ‌چیز منتشر نشد، ظرفیت را پایین نمی‌آورد.
  // همان منطق inconclusive در یادگیری: آزمایش بی‌اعتبار، آزمایش نیست.
  const done = history.filter(h => h.planned > 0 && !h.externalBlock);
  const ratio = done.length
    ? done.reduce((s, h) => s + Math.min(1, h.published / h.planned), 0) / done.length
    : 0.6;

  return {
    statedPerWeek:  stated,
    windowDays:     days,
    ratio:          Number(ratio.toFixed(2)),
    basedOn:        done.length ? `${done.length} دور معتبر گذشته` : 'ضریب پیش‌فرض — هنوز سابقه‌ای نیست',
    excluded:       history.length - done.length,   // دورهایی که به دلیل بیرونی کنار گذاشته شدند
    // ⚠️ واحد: کل قطعه‌ها در تمام پنجره، نه در هفته
    realisticTotal: Math.max(1, Math.round(stated * weeks * ratio)),
    statedTotal:    Math.max(1, Math.round(stated * weeks))
  };
}

/**
 * کفایت شواهد — این قضاوت عمداً در کد است، نه در پرامپت.
 *
 * چرا: تشخیص اینکه «با این تعداد نمونه چه ادعایی مجاز است» ریاضی است نه قضاوت.
 * اگر به مدل بسپاریم، بالاخره یک روز از آن رد می‌شود و عددی می‌سازد که پشتش چیزی نیست.
 * پس حکم را کد صادر می‌کند و به‌عنوان ورودی به مدل داده می‌شود.
 *
 * آستانه‌ها عمداً سخت‌گیرانه‌اند. با حجم کم محتوا، خطای «الگوی خیالی»
 * از خطای «الگوی از دست رفته» خیلی پرهزینه‌تر است.
 */
export function evidenceStrength({ samples = 0, variantsCompared = 1, biggestGapRatio = 1 } = {}) {
  const n = Number(samples) || 0;

  let allowed, reason;
  if (n < 3) {
    allowed = 'describe_only';
    reason = `${n} نمونه. فقط می‌شود گفت چه اتفاقی افتاد، نه اینکه چرا.`;
  } else if (n < 5) {
    allowed = 'describe_only';
    reason = `${n} نمونه. برای مقایسه کافی نیست.`;
  } else if (n < 8) {
    allowed = 'weak_observation';
    reason = `${n} نمونه. می‌شود یک مشاهده‌ی تکرارشونده را گفت، ولی باید «ضعیف» برچسب بخورد.`;
  } else if (variantsCompared > 2) {
    allowed = 'weak_observation';
    reason = `${n} نمونه ولی ${variantsCompared} چیز هم‌زمان فرق داشت. نتیجه قابل نسبت‌دادن نیست.`;
  } else {
    allowed = 'propose_hypothesis';
    reason = `${n} نمونه و ${variantsCompared} متغیر. می‌شود یک فرضیه پیشنهاد داد — نه یک واقعیت.`;
  }

  // اختلاف کمتر از دو برابر در این ابعاد نمونه، نویز است
  const gapMeaningful = biggestGapRatio >= 2;
  if (allowed === 'propose_hypothesis' && !gapMeaningful) {
    allowed = 'weak_observation';
    reason += ` اختلاف بین بهترین و بدترین کمتر از دو برابر است — در این تعداد نمونه، نویز.`;
  }

  return {
    samples: n,
    allowed,          // describe_only | weak_observation | propose_hypothesis
    reason,
    neverAllowed: ['نرخ صنعتی', 'معناداری آماری', 'رتبه‌بندی قطعی', 'پیش‌بینی عددی فروش'],
    needForNext: n < 8 ? `برای پیشنهاد الگو حداقل ${8 - n} نمونه‌ی دیگر لازم است` : null
  };
}

/**
 * خستگی نخ — جلوگیری از کوبیدن به درِ فرسوده.
 *
 * سیاست ساده‌ی «همیشه به بدترین گلوگاه بزن» نوسان می‌کند:
 * A را درست می‌کنی، B بدترین می‌شود، B را درست می‌کنی، A دوباره بدترین می‌شود.
 * در شبیه‌سازی ده دوره، دو گلوگاه هرکدام سه بار هدف شدند با بازده نزولی.
 *
 * این تابع جلوی تکرار را می‌گیرد مگر اینکه رویکرد واقعاً متفاوت باشد.
 */
export function threadFatigue(campaignHistory = [], target) {
  const hits = campaignHistory.filter(c => c.target === target);
  const productive = hits.filter(c => c.outcome === 'supported').length;
  const approaches = new Set(hits.map(c => c.approach).filter(Boolean));

  const tired = hits.length >= 3 && productive === 0;

  return {
    target,
    timesTargeted: hits.length,
    productiveHits: productive,
    approachesTried: [...approaches],
    tired,
    verdict: tired
      ? `این گلوگاه ${hits.length} بار هدف شده و هیچ‌بار جواب نداده. با همان رویکردها دوباره سراغش نرو.`
      : hits.length >= 2 && productive === 0
      ? `${hits.length} بار امتحان شده بدون نتیجه. اگر دوباره می‌روی، رویکرد باید واقعاً متفاوت باشد.`
      : null,
    // اگر همه‌ی نخ‌ها خسته‌اند، مسئله جای دیگری است
    suggestStepBack: tired && approaches.size >= 2
  };
}

/**
 * فشرده‌سازی حافظه — قطعی، در کد، قبل از هر مرحله.
 *
 * نسخه‌ی اول این قاعده اشتباهاً داخل یکی از پرامپت‌ها نوشته شده بود.
 * دو ایراد داشت: تورم حافظه همه‌ی مرحله‌ها را می‌گیرد نه یکی، و
 * فشرده‌کردن یک عمل قطعی است — اگر به مدل سپرده شود، هر بار جور دیگری فشرده می‌کند
 * و حافظه بین اجراها ناپایدار می‌شود.
 *
 * سه چیز هرگز فشرده نمی‌شوند:
 *   ۱. گزاره‌هایی که کاربر مستقیماً گفته و هنوز درباره‌ی وضع فعلی‌اند
 *   ۲. محدودیت‌ها
 *   ۳. فرضیه‌های زنده (نه بازنشسته، نه ارتقایافته)
 */
export function condenseMemory(knowledge, { keepRecentCycles = 3, threshold = 30 } = {}) {
  const k = structuredClone(knowledge);
  const stated = k.userStated || [];
  if (stated.length <= threshold) return { knowledge: k, condensed: 0 };

  const cycleOf = s => {
    const m = String(s.topic || '').match(/دور\s*(\d+)/);
    return m ? parseInt(m[1], 10) : null;
  };
  const cycles = stated.map(cycleOf).filter(Number.isFinite);
  const newest = cycles.length ? Math.max(...cycles) : 0;
  const cutoff = newest - keepRecentCycles;

  const old  = stated.filter(s => { const c = cycleOf(s); return c !== null && c <= cutoff; });
  const keep = stated.filter(s => !old.includes(s));

  if (old.length < 3) return { knowledge: k, condensed: 0 };

  const cs = old.map(cycleOf).filter(Number.isFinite);
  k.userStated = [
    ...keep,
    { topic: `خلاصه‌ی دورهای ${Math.min(...cs)} تا ${Math.max(...cs)}`,
      value: old.map(o => o.value).join(' · ').slice(0, 600),
      status: 'fact', source: 'فشرده‌شده از گزارش‌های کاربر' }
  ];
  return { knowledge: k, condensed: old.length, replacedWith: 1 };
}

/**
 * برش شناخت — هر مرحله فقط آنچه لازم دارد را می‌گیرد.
 *
 * اندازه‌گیری نشان داد ۷۹٪ حجم پرامپت‌ها داده است نه دستورالعمل،
 * و همان یک شیء شناخت عیناً به چهار مرحله فرستاده می‌شد.
 *
 * این فقط بهینه‌سازی هزینه نیست: دادن داده‌ی بی‌ربط به یک مرحله،
 * از همان جنس خطای «پرسیدن چیزی که کد می‌داند» است — تمرکز را کم می‌کند.
 */
export function knowledgeFor(stage, k = {}) {
  // برش، بعد پاک‌کردن مهر تولید — مهر هیچ تصمیمی را عوض نمی‌کند
  return stripMeta(sliceKnowledge(stage, k));
}

function sliceKnowledge(stage, k = {}) {
  // سازگاری با خروجی‌های قدیمی که usable بولی بود.
  // بدون این، برش صفر محصول برمی‌گرداند و کمپین بی‌سوژه می‌ماند — بی‌سروصدا.
  const usable = (k.productUsability || []).filter(p =>
    p.usable === 'yes' || p.usable === true);

  const base = {
    business:    k.business,
    constraints: k.constraints,
    userStated:  k.userStated,
    notChecked:  k.notChecked
  };

  switch (stage) {
    case 'questions':
      // نیاز دارد بداند چه چیزی *نمی‌داند*، نه فهرست کامل محصولات
      return { ...base,
        absences:   k.absences,
        economics:  k.economics,
        audience:   k.audience,
        needForNext: k.learningMemory?.needForNext,
        usableCount: usable.length,
        unsureCount: (k.productUsability || []).filter(p => p.usable === 'unknown').length };

    case 'market':
      // بازار به موجودی تک‌تک اقلام کاری ندارد
      return { ...base,
        audience:    k.audience,
        competitors: k.competitors,
        brand:       k.brand,
        categories:  [...new Set((k.products || []).map(p => p.name))].slice(0, 12) };

    case 'content':
      // خواندن محتوای گذشته به فهرست موجودی کاری ندارد — به صدا و مخاطب دارد
      return { ...base,
        brand:    k.brand,
        audience: k.audience,
        absences: k.absences };

    case 'strategy':
      // فقط اقلام قابل استفاده، با نام — نه کل کارت محصول
      return { ...base,
        brand:     k.brand,
        audience:  k.audience,
        economics: k.economics,
        absences:  k.absences,
        reach:     k.reach,
        learningMemory: k.learningMemory,
        usableProducts: usable.map(p => p.product) };

    case 'campaign':
      return { ...base,
        learningMemory: k.learningMemory,
        usableProducts: usable.map(p => p.product) };

    case 'evidence':
      // دروازه‌ی شواهد به همه‌چیز نیاز دارد — اینجا برش نمی‌زنیم
      return k;

    default:
      return k;
  }
}

